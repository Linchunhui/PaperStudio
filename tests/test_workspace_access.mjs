import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../web/app.js',import.meta.url),'utf8').replace(/^import .*$/m,'const mountReader=()=>{};').replace(/^export /gm,'');
const settle=async()=>{for(let i=0;i<50;i++)await Promise.resolve();};
async function boot({user={id:'u1',username:'reader',role:'user',inbox_id:'inbox-u1'},setup=false,search='?view=catalog',mobile=false}={}){
  const elements=new Map(),requests=[],handlers=new Map(),storage=[],focusLog=[];let doc;
  const el=key=>{if(!elements.has(key))elements.set(key,{innerHTML:'',textContent:'',outerHTML:'',hidden:false,isConnected:true,attributes:{},setAttribute(name,value){this.attributes[name]=value;},removeAttribute(name){delete this.attributes[name];},focus(){focusLog.push(key);if(doc)doc.activeElement=this;},classList:{add(){},remove(){},toggle(){}},addEventListener(type,handler){handlers.set(key+':'+type,handler);}});return elements.get(key);};
  class Fields{constructor(form){this.values=new Map(Object.entries(form?.data||{}));}get(key){return this.values.get(key)??null;}set(key,value){this.values.set(key,value);}entries(){return this.values.entries();}}
  const item={id:'schedule-row',title:'An actual paper',url:'https://example.org/whole-conference-program',resolve:{action:'search',url:null,query:'An actual paper'},directions:['OCR'],conferences:[{conference:'ICLR',year:2026,presentation:'Oral',verification_status:'confirmed'}],provenance:[],source_ids:['conference']};
  const context=vm.createContext({console,URL,URLSearchParams,Headers,AbortController,FormData:Fields,location:{pathname:'/',search,assign(){}},history:{replaceState(){}},document:(doc={querySelector:el}),window:{addEventListener(){},matchMedia(){return {matches:mobile,addEventListener(){}};}},localStorage:{getItem(key){storage.push(key);return null;},setItem(){}},setTimeout(){return 1;},clearTimeout(){},fetch:async(path,request={})=>{
    requests.push({path,request});let result;
    if(path==='/api/auth/session')result={user,setup_required:setup,csrf_token:user?'csrf-for-user':null};
    else if(path==='/api/projects')result=[{id:'inbox-u1',name:'个人收件箱',can_edit:true}];
    else if(path==='/api/imports')result=[];
    else if(path==='/api/catalog/stats')result={total:1,source_records:2,institutions:[{name:'Example University',count:1}],conferences:[{name:'ICLR',count:1}],directions:[{name:'OCR',count:1}],by_year:[],sources:[]};
    else if(path.startsWith('/api/catalog?'))result={items:[item],total:1,pages:1,page:1};
    else if(path.startsWith('/api/discovery/'))result={items:[],statuses:[],directions:[{name:'OCR',count:1}]};
    else if(path==='/api/ping')result={ok:true};
    else if(['/api/capabilities','/api/skills','/api/discovery/config','/api/sources'].includes(path))throw new Error('Ordinary user must not request admin endpoint '+path);
    else throw new Error('Unexpected request '+path);
    return {ok:true,status:200,headers:new Headers({'content-type':'application/json'}),json:async()=>result};
  }});
  vm.runInContext(source,context);await settle();
  const click=async dataset=>{await handlers.get('#app:click')({target:{closest:()=>({dataset,isConnected:true,disabled:false})}});await settle();};
  return {context,elements,requests,storage,click,el,handlers,focusLog};
}
const anonymous=await boot({user:null});
assert.match(anonymous.el('#app').innerHTML,/登录研究空间/);
assert.equal(anonymous.requests.length,1,'Anonymous session cannot fetch private project or catalog APIs');
const setup=await boot({user:null,setup:true});
assert.match(setup.el('#app').innerHTML,/初始化令牌/);
assert.match(setup.el('#app').innerHTML,/minlength="12"/);
const normal=await boot();
assert.match(normal.el('#app').innerHTML,/论文索引/);
assert.doesNotMatch(normal.el('#app').innerHTML,/管理员设置|Skills 与服务|catalog-import-form|catalog-hf-form/);
assert.ok(normal.storage.every(key=>key.endsWith(':u1')),'Browser preferences must be isolated by account');
await normal.context.api('/ping',{method:'POST',body:{value:1}});
const mutation=normal.requests.find(row=>row.path==='/api/ping');
assert.equal(mutation.request.headers.get('X-CSRF-Token'),'csrf-for-user');
assert.equal(mutation.request.credentials,'same-origin');
assert.doesNotMatch(normal.el('#app').innerHTML,/data-view="recommendations"|data-view="imports"/);
assert.match(normal.el('#app').innerHTML,/id="index-panel"/);
const small=await boot({mobile:true});
assert.equal(small.el('#workspace-navigation').inert,true,'Collapsed mobile navigation is not tabbable');
await small.click({action:'toggle-navigation'});
assert.equal(small.el('#workspace-nav-toggle').attributes['aria-expanded'],'true');
assert.equal(small.el('#main-content').inert,true);
assert.equal(small.el('#workspace-navigation').attributes['aria-modal'],'true');
small.handlers.get('#app:keydown')({key:'Escape',preventDefault(){}});
assert.equal(small.el('#workspace-nav-toggle').attributes['aria-expanded'],'false');
assert.equal(small.el('#main-content').inert,false);
assert.equal(small.focusLog.at(-1),'#workspace-nav-toggle','Escape returns focus to the navigation opener');
await small.click({view:'discover'});
assert.ok(small.focusLog.includes('.workspace-content h1'),'Intentional navigation moves focus to the page heading');
await small.click({view:'catalog'});const focusCount=small.focusLog.length;
await small.click({action:'refresh-catalog'});assert.equal(small.focusLog.length,focusCount,'Background catalog refresh must not move keyboard focus');
console.log('PASS: session gate, first-run setup, ordinary-user endpoint isolation, account preferences, CSRF, consolidated navigation and mobile focus');
