import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {runtime,load} from './ui-harness.mjs';
const c=runtime();vm.runInContext(fs.readFileSync(new URL('../web/vendor/katex.min.js',import.meta.url),'utf8'),c);load(c,'math.js');load(c,'paper-insights.js');
assert.match(c.mathText('Inline $\\frac{a}{b}$ formula'),/<mfrac>/);
assert.match(c.mathText('$$\\sum_{i=1}^n x_i$$'),/display="block"/);
assert.match(c.mathText('\\(x^2\\)'),/<msup>/);
assert.match(c.mathText('\\[x^2\\]'),/math-display/);
assert.match(c.mathMarkdown('First\n$$\n\\frac{1}{2}\n$$\nLast'),/<mfrac>/);
assert.match(c.insightMarkup({abstract:'$x^2$',structured:{research_problem:'$\\alpha$',methods:['$a_i$'],experiments:['$$a=b$$']}}),/<math/);
assert.doesNotMatch(c.mathText('`$x$` and ```$y$```'),/<math/);
assert.equal(c.mathText('Cost $20 and $30'),'Cost $20 and $30');
assert.match(c.mathText('<img onerror=bad()>'),/&lt;img/);
assert.doesNotMatch(c.mathText('$\\href{javascript:alert(1)}{x}$'),/href="javascript|<script|<img/);
assert.match(c.mathText('$\\invalidmacro{x}$'),/math-source/);
assert.match(c.mathText('$\\gdef\\evil{BAD}\\evil$'),/BAD/);
assert.doesNotMatch(c.mathText('$\\evil$'),/>BAD</,'Macros cannot leak between papers');
const source=c.mathText('$\\frac{x}{y}$');assert.match(source,/data-math-source="\$\\frac\{x\}\{y\}\$"/);
console.log('PASS: real local KaTeX fractions/scripts/blocks, multi-line Markdown, shared insight rendering, currency/code, XSS and macro isolation');
